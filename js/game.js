// KEYBOARD CONTROLS
// ═══════════════════════════════════════════════════════════════════════════
function handleKeyboardEvent(e) {
    // Only process when game page is active
    const gamePage = document.getElementById('page-game');
    if (!gamePage || !gamePage.classList.contains('active')) return;

    // Don't intercept if user is typing inside an input/textarea
    const activeTag = document.activeElement ? document.activeElement.tagName.toLowerCase() : '';
    if (activeTag === 'input' || activeTag === 'textarea' || document.activeElement?.isContentEditable) {
        return;
    }

    // Modal open? Space/Enter advances to next word
    const overlay = document.getElementById('scrambleModalOverlay');
    if (overlay && overlay.style.display === 'flex') {
        if (e.key === 'Escape') {
            closeScrambleCelebration();
        } else if (e.key === 'Enter') {
            newScrambleWord();
        }
        return;
    }

    if (e.key === 'Backspace') {
        e.preventDefault();
        // Remove rightmost filled, non-hint slot
        for (let i = answerSlots.length - 1; i >= 0; i--) {
            if (answerSlots[i] && !answerSlots[i].isHint) {
                handleSlotClick(i);
                break;
            }
        }
    } else if (e.key === 'Enter') {
        e.preventDefault();
        checkScrambleWord();
    } else if (e.key === ' ') {
        e.preventDefault();
        shuffleScrambleBank();
    } else if (/^[a-zA-Z]$/.test(e.key)) {
        const typedChar = e.key.toUpperCase();
        // Find an unused bank tile matching this character
        const tile = scrambledBank.find(t => !t.used && t.char === typedChar);
        if (tile) {
            e.preventDefault();
            handleTileClick(tile.id);
        }
    }
}

