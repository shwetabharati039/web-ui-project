export function newScrambleWord(specificIndex = null) {
    closeScrambleCelebration();
    clearFeedback();

    if (specificIndex !== null && specificIndex >= 0 && specificIndex < REFLECTIVE_WORDS.length) {
        currentWordIndex = specificIndex;
    } else {
        // Pick random index different from current if possible
        let nextIdx = Math.floor(Math.random() * REFLECTIVE_WORDS.length);
        if (REFLECTIVE_WORDS.length > 1 && nextIdx === currentWordIndex) {
            nextIdx = (nextIdx + 1) % REFLECTIVE_WORDS.length;
        }
        currentWordIndex = nextIdx;
    }

    currentWordObj = REFLECTIVE_WORDS[currentWordIndex];
    const targetWord = currentWordObj.word.toUpperCase();
    hintsRemaining = 2;

    // Prepare scrambled tiles
    const scrambledChars = scrambleWordLetters(targetWord);
    scrambledBank = scrambledChars.map((ch, idx) => ({
        id: idx,
        char: ch,
        used: false
    }));

    // Prepare empty answer slots
    answerSlots = new Array(targetWord.length).fill(null);

    // Update UI elements
    const catEl = document.getElementById('scrambleCategory');
    const clueEl = document.getElementById('scrambleClue');
    const lenEl = document.getElementById('scrambleLengthTag');
    const hintCountEl = document.getElementById('scrambleHintCount');
    const hintBtn = document.getElementById('scrambleHintBtn');

    if (catEl) catEl.innerHTML = `<i class="fa-solid fa-seedling"></i> ${currentWordObj.category}`;
    if (clueEl) clueEl.textContent = currentWordObj.clue;
    if (lenEl) lenEl.textContent = `${targetWord.length} letters`;
    if (hintCountEl) hintCountEl.textContent = hintsRemaining;
    if (hintBtn) hintBtn.disabled = false;

    renderSlots();
    renderBank();
}
window.newScrambleWord = newScrambleWord;

export function skipScrambleWord() {
    playSynthesizedSound('shuffle');
    newScrambleWord();
}
window.skipScrambleWord = skipScrambleWord;

// Render answer slots
function renderSlots() {
    const container = document.getElementById('scrambleSlots');
    if (!container) return;
    container.innerHTML = '';

    answerSlots.forEach((slot, idx) => {
        const slotEl = document.createElement('div');
        slotEl.className = 'scramble-slot';
        slotEl.dataset.index = idx;

        if (slot) {
            slotEl.classList.add('filled');
            slotEl.textContent = slot.char;
            if (slot.isHint) {
                slotEl.classList.add('locked');
                slotEl.title = 'Revealed by hint';
            } else {
                slotEl.title = 'Click to return letter to bank';
                slotEl.onclick = () => handleSlotClick(idx);
            }
        } else {
            slotEl.classList.add('empty');
            // Show subtle index indicator or blank
            slotEl.textContent = '';
        }

        container.appendChild(slotEl);
    });
}

// Render letter bank
function renderBank() {
    const container = document.getElementById('scrambleBank');
    if (!container) return;
    container.innerHTML = '';

    scrambledBank.forEach(tile => {
        const tileEl = document.createElement('button');
        tileEl.className = 'scramble-tile';
        tileEl.dataset.id = tile.id;
        tileEl.textContent = tile.char;

        if (tile.used) {
            tileEl.classList.add('used');
            tileEl.disabled = true;
        } else {
            tileEl.onclick = () => handleTileClick(tile.id);
        }

        container.appendChild(tileEl);
    });
}

// Clicking a bank tile moves it into the first empty slot
export function handleTileClick(tileId) {
    const tile = scrambledBank.find(t => t.id === tileId);
    if (!tile || tile.used) return;

    // Find first empty slot
    const firstEmptyIndex = answerSlots.findIndex(s => s === null);
    if (firstEmptyIndex === -1) return; // all slots filled

    tile.used = true;
    answerSlots[firstEmptyIndex] = {
        id: tile.id,
        char: tile.char,
        isHint: false
    };

    playSynthesizedSound('tile-click');
    clearFeedback();
    renderSlots();
    renderBank();

    // If now full, subtle prompt to check
    if (answerSlots.every(s => s !== null)) {
        const allFilled = true;
    }
}
window.handleTileClick = handleTileClick;

// Clicking a filled slot returns that letter back to the bank
export function handleSlotClick(slotIndex) {
    const slot = answerSlots[slotIndex];
    if (!slot || slot.isHint) return;

    // Release tile in bank
    const tile = scrambledBank.find(t => t.id === slot.id);
    if (tile) tile.used = false;

    answerSlots[slotIndex] = null;

    playSynthesizedSound('slot-click');
    clearFeedback();
    renderSlots();
    renderBank();
}
window.handleSlotClick = handleSlotClick;

// Return all non-hint letters to bank
export function clearScrambleAttempt() {
    let clearedAny = false;
    answerSlots.forEach((slot, idx) => {
        if (slot && !slot.isHint) {
            const tile = scrambledBank.find(t => t.id === slot.id);
            if (tile) tile.used = false;
            answerSlots[idx] = null;
            clearedAny = true;
        }
    });

    if (clearedAny) {
        playSynthesizedSound('slot-click');
    }
    clearFeedback();
    renderSlots();
    renderBank();
}
window.clearScrambleAttempt = clearScrambleAttempt;

// Shuffle available letter bank
export function shuffleScrambleBank() {
    playSynthesizedSound('shuffle');

    // Shuffle only unused tiles
    const unusedIndices = [];
    scrambledBank.forEach((t, i) => {
        if (!t.used) unusedIndices.push(i);
    });

    for (let i = unusedIndices.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        const idxA = unusedIndices[i];
        const idxB = unusedIndices[j];
        const tmp = scrambledBank[idxA];
        scrambledBank[idxA] = scrambledBank[idxB];
        scrambledBank[idxB] = tmp;
    }

    renderBank();
}
window.shuffleScrambleBank = shuffleScrambleBank;

// Reveal a correct letter in place
export function useScrambleHint() {
    if (!currentWordObj || hintsRemaining <= 0) return;

    const targetWord = currentWordObj.word.toUpperCase();

    // Find first slot that does not already hold the correct letter
    let targetSlotIdx = -1;
    for (let i = 0; i < targetWord.length; i++) {
        if (!answerSlots[i] || answerSlots[i].char !== targetWord[i]) {
            targetSlotIdx = i;
            break;
        }
    }

    if (targetSlotIdx === -1) return; // Word is already correctly formed

    const neededChar = targetWord[targetSlotIdx];

    // If this slot currently has an incorrect letter, return it to bank first
    if (answerSlots[targetSlotIdx] && !answerSlots[targetSlotIdx].isHint) {
        const wrongTile = scrambledBank.find(t => t.id === answerSlots[targetSlotIdx].id);
        if (wrongTile) wrongTile.used = false;
        answerSlots[targetSlotIdx] = null;
    }

    // Find an unused bank tile matching neededChar
    let matchingTile = scrambledBank.find(t => !t.used && t.char === neededChar);

    // If none unused, take it from another non-hint slot that is using it incorrectly
    if (!matchingTile) {
        for (let j = 0; j < answerSlots.length; j++) {
            if (j !== targetSlotIdx && answerSlots[j] && !answerSlots[j].isHint && answerSlots[j].char === neededChar) {
                const tileId = answerSlots[j].id;
                answerSlots[j] = null;
                matchingTile = scrambledBank.find(t => t.id === tileId);
                break;
            }
        }
    }

    if (matchingTile) {
        matchingTile.used = true;
        answerSlots[targetSlotIdx] = {
            id: matchingTile.id,
            char: neededChar,
            isHint: true
        };
        hintsRemaining--;

        const countEl = document.getElementById('scrambleHintCount');
        const btn = document.getElementById('scrambleHintBtn');
        if (countEl) countEl.textContent = hintsRemaining;
        if (btn && hintsRemaining <= 0) btn.disabled = true;

        playSynthesizedSound('hint');
        showFeedback(`Hint: Placed letter "${neededChar}" in position ${targetSlotIdx + 1}`, 'info');
        renderSlots();
        renderBank();
    }
}
window.useScrambleHint = useScrambleHint;

// Check user's attempt
export function checkScrambleWord() {
    if (!currentWordObj) return;

    const targetWord = currentWordObj.word.toUpperCase();

    // Check if all slots filled
    const hasEmptySlot = answerSlots.some(s => s === null);
    if (hasEmptySlot) {
        showFeedback('Place all letters into the slots before checking!', 'warning');
        shakeSlots();
        playSynthesizedSound('error');
        return;
    }

    const currentAttempt = answerSlots.map(s => s.char).join('');

    if (currentAttempt === targetWord) {
        // SOLVED!
        playSynthesizedSound('success');
        userStats.solved++;
        userStats.streak++;
        const pointsEarned = Math.max(10, targetWord.length * 10 - (2 - hintsRemaining) * 5);
        userStats.score += pointsEarned;
        saveUserStats();

        showCelebration(currentWordObj, pointsEarned);
    } else {
        // INCORRECT
        playSynthesizedSound('error');
        shakeSlots();
        showFeedback('Not quite right. Try rearranging the letters or use a hint!', 'error');
    }
}
window.checkScrambleWord = checkScrambleWord;

function shakeSlots() {
    const el = document.getElementById('scrambleSlots');
    if (!el) return;
    el.classList.remove('shake');
    void el.offsetWidth; // trigger reflow
    el.classList.add('shake');
    setTimeout(() => el.classList.remove('shake'), 600);
}

