// "Write in Diary" button handler:
// Navigates to New Entry, pre-populates reflection title and prompt
export function writeAboutScrambleWord() {
    if (!currentWordObj) return;

    const wordObj = currentWordObj;
    closeScrambleCelebration();

    if (typeof window.navigateTo === 'function') {
        window.navigateTo('new-entry');
    }

    setTimeout(() => {
        const titleInput = document.getElementById('entryTitle');
        const contentDiv = document.getElementById('entryContent');

        const titleText = `Reflection: ${wordObj.word.charAt(0) + wordObj.word.slice(1).toLowerCase()}`;
        if (titleInput && (!titleInput.value || titleInput.value.trim() === '')) {
            titleInput.value = titleText;
        }

        if (contentDiv) {
            const promptMarkup = `<p><strong>${wordObj.prompt}</strong></p><p><em>"${wordObj.quote}"</em></p><p><br></p>`;
            contentDiv.innerHTML = promptMarkup;
            contentDiv.focus();

            // Place cursor at the end
            try {
                const range = document.createRange();
                const sel = window.getSelection();
                range.selectNodeContents(contentDiv);
                range.collapse(false);
                sel.removeAllRanges();
                sel.addRange(range);
            } catch (e) {}
        }
    }, 150);
}
window.writeAboutScrambleWord = writeAboutScrambleWord;

